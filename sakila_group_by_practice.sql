

USE sakila;

-- Q1. Find the total number of films for each rating.

SELECT rating, COUNT(film_id)
FROM film
GROUP BY rating;


-- Q2. Find the average film length for each rating.

SELECT rating, AVG(length)
FROM film
GROUP BY rating;


-- Q3. Count the number of customers belonging to each store.

SELECT store_id, COUNT(customer_id)
FROM customer
GROUP BY store_id;


-- Q4. Calculate the total payment amount processed
-- by each staff member.

SELECT staff_id, SUM(amount)
FROM payment
GROUP BY staff_id;


-- Q5. Find the minimum and maximum replacement cost
-- for films of each rating.

SELECT
    rating,
    MIN(replacement_cost),
    MAX(replacement_cost)
FROM film
GROUP BY rating;


-- Q6. Find customers who have made more than 20 rentals.
-- Show customer IDs and rental counts, highest first.

SELECT
    customer_id,
    COUNT(rental_id)
FROM rental
GROUP BY customer_id
HAVING COUNT(rental_id) > 20
ORDER BY COUNT(rental_id) DESC;


-- Q7. Find the average payment amount per customer.
-- Show only customers whose average payment exceeds 3.

SELECT customer_id, AVG(amount)
FROM payment
GROUP BY customer_id
HAVING AVG(amount) > 3;


-- Q8. Count films for each rental duration.
-- Show only durations associated with at least 50 films.

SELECT
    rental_duration,
    COUNT(film_id) AS total_films
FROM film
GROUP BY rental_duration
HAVING COUNT(film_id) >= 50;


-- Q9. Show total amount paid by each customer,
-- including first name and last name.
-- Order by total paid, highest first.

SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    SUM(p.amount)
FROM customer c
INNER JOIN payment p
    ON c.customer_id = p.customer_id
GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name
ORDER BY SUM(p.amount) DESC;


